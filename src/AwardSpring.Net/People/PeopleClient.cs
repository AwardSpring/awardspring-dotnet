        ArchivePeopleRequest request,
        RequestOptions? options = null,
        CancellationToken cancellationToken = default
    )
    {
        return new WithRawResponseTask<PersonV1>(
            ArchiveAsyncCore(request, options, cancellationToken)
        );
    }

